public class IT26101661Lab2Q3 {
    public static void main(String[] args) {

        double sideA = 3;
        double sideB = 4;
        double hypotenuse;

        // Calculate the hypotenuse
        hypotenuse = Math.sqrt((sideA * sideA) + (sideB * sideB));

        System.out.println("Length of the hypotenuse: " + hypotenuse);
    }
}
